"""Export a suite to pytest, unittest, JSON, TOML, or text.

Generated Python embeds literals. It does not exec suite contents.
"""

from __future__ import annotations

import json
from pathlib import Path

from lupaxa.regexlab.errors import UsageError
from lupaxa.regexlab.flagset import parse_flags
from lupaxa.regexlab.suite import Suite, suite_to_dict

_FORMATS = {"pytest", "unittest", "json", "toml", "text"}


def export_suite(suite: Suite, fmt: str, output: Path | None, *, force: bool) -> str:
    if fmt not in _FORMATS:
        raise UsageError(f"unknown export format {fmt!r}")
    if fmt == "pytest":
        text = _pytest(suite)
    elif fmt == "unittest":
        text = _unittest(suite)
    elif fmt == "json":
        text = json.dumps(suite_to_dict(suite), ensure_ascii=False, indent=2) + "\n"
    elif fmt == "toml":
        text = _toml(suite)
    else:
        text = _text(suite)
    if output is not None:
        if output.exists() and not force:
            raise UsageError(f"{output} already exists. Pass --force to overwrite.")
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8")
    return text


def _cases(suite: Suite) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for case in suite.tests:
        row: dict[str, object] = {
            "name": case.name,
            "input": case.text,
            "should_match": case.should_match,
            "span": list(case.span) if case.span is not None else None,
            "groups": case.groups,
            "groupdict": case.groupdict,
            "count": case.count,
            "replacement": case.replacement,
            "expected_replacement": case.expected_replacement,
            "expected_split": case.expected_split,
            "pattern": case.pattern,
            "mode": case.mode,
        }
        rows.append(row)
    return rows


def _pytest(suite: Suite) -> str:
    flags = parse_flags(suite.flags, engine=suite.engine)
    bits = _flag_bits(flags)
    cases = _cases(suite)
    return (
        '"""Generated by regex-lab. Suite values are literals, not exec\'d."""\n'
        "import re\n\n"
        "import pytest\n\n"
        f"PATTERN = {suite.pattern!r}\n"
        f"FLAGS = {bits}\n"
        f"MODE = {suite.mode!r}\n"
        f"CASES = {cases!r}\n\n\n"
        "def _safe_iter(compiled: re.Pattern[str], text: str) -> list[re.Match[str]]:\n"
        "    found: list[re.Match[str]] = []\n"
        "    pos = 0\n"
        "    while pos <= len(text) and len(found) < 1000:\n"
        "        match = compiled.search(text, pos)\n"
        "        if match is None:\n"
        "            break\n"
        "        found.append(match)\n"
        "        nxt = match.end()\n"
        "        pos = nxt if nxt > pos else pos + 1\n"
        "    return found\n\n\n"
        '@pytest.mark.parametrize("case", CASES, ids=[item["name"] for item in CASES])\n'
        "def test_generated(case: dict) -> None:\n"
        "    compiled = re.compile(PATTERN, FLAGS)\n"
        "    mode = case['mode'] or MODE\n"
        "    if case['expected_split'] is not None:\n"
        "        assert compiled.split(case['input']) == case['expected_split']\n"
        "        return\n"
        "    if case['replacement'] is not None:\n"
        "        assert compiled.sub("
        "case['replacement'], case['input']) == case['expected_replacement']\n"
        "    matches = _safe_iter(compiled, case['input']) "
        "if mode in {'finditer', 'findall'} else []\n"
        "    if mode == 'fullmatch':\n"
        "        found = compiled.fullmatch(case['input'])\n"
        "        matches = [found] if found else []\n"
        "    elif mode == 'match':\n"
        "        found = compiled.match(case['input'])\n"
        "        matches = [found] if found else []\n"
        "    elif mode == 'search':\n"
        "        found = compiled.search(case['input'])\n"
        "        matches = [found] if found else []\n"
        "    if case['should_match'] is True:\n"
        "        assert matches\n"
        "    if case['should_match'] is False:\n"
        "        assert not matches\n"
        "    if case['count'] is not None:\n"
        "        assert len(matches) == case['count']\n"
        "    if case['span'] is not None and matches:\n"
        "        assert list(matches[0].span()) == case['span']\n"
        "    if case['groups'] is not None and matches:\n"
        "        assert list(matches[0].groups()) == case['groups']\n"
        "    if case['groupdict'] is not None and matches:\n"
        "        assert matches[0].groupdict() == case['groupdict']\n"
    )


def _unittest(suite: Suite) -> str:
    flags = parse_flags(suite.flags, engine=suite.engine)
    bits = _flag_bits(flags)
    cases = _cases(suite)
    return (
        '"""Generated by regex-lab. Suite values are literals, not exec\'d."""\n'
        "import re\n"
        "import unittest\n\n"
        f"PATTERN = {suite.pattern!r}\n"
        f"FLAGS = {bits}\n"
        f"MODE = {suite.mode!r}\n"
        f"CASES = {cases!r}\n\n\n"
        "class GeneratedRegexTest(unittest.TestCase):\n"
        "    def test_cases(self) -> None:\n"
        "        compiled = re.compile(PATTERN, FLAGS)\n"
        "        for case in CASES:\n"
        "            with self.subTest(case=case['name']):\n"
        "                mode = case['mode'] or MODE\n"
        "                found = None\n"
        "                if mode == 'fullmatch':\n"
        "                    found = compiled.fullmatch(case['input'])\n"
        "                elif mode == 'match':\n"
        "                    found = compiled.match(case['input'])\n"
        "                elif mode == 'search':\n"
        "                    found = compiled.search(case['input'])\n"
        "                if case['should_match'] is True:\n"
        "                    self.assertIsNotNone(found)\n"
        "                if case['should_match'] is False:\n"
        "                    self.assertIsNone(found)\n"
        "                if case['groups'] is not None and found is not None:\n"
        "                    self.assertEqual(list(found.groups()), case['groups'])\n\n\n"
        "if __name__ == '__main__':\n"
        "    unittest.main()\n"
    )


def _toml(suite: Suite) -> str:
    lines = [
        f'schema_version = "{suite.schema_version}"',
        f"name = {_q(suite.name)}",
        f"engine = {_q(suite.engine)}",
        f"pattern = {_q(suite.pattern)}",
        f"mode = {_q(suite.mode)}",
        f"flags = {_q(suite.flags)}",
    ]
    for case in suite.tests:
        lines.append("")
        lines.append("[[tests]]")
        lines.append(f"name = {_q(case.name)}")
        lines.append(f"input = {_q(case.text)}")
        if case.should_match is not None:
            lines.append(f"should_match = {'true' if case.should_match else 'false'}")
        if case.span is not None:
            lines.append(f"span = [{case.span[0]}, {case.span[1]}]")
        if case.groups is not None:
            lines.append("groups = [" + ", ".join(_q(item or "") for item in case.groups) + "]")
        if case.groupdict is not None:
            pairs = ", ".join(f"{key} = {_q(value or '')}" for key, value in case.groupdict.items())
            lines.append(f"groupdict = {{ {pairs} }}")
        if case.replacement is not None:
            lines.append(f"replacement = {_q(case.replacement)}")
        if case.expected_replacement is not None:
            lines.append(f"expected_replacement = {_q(case.expected_replacement)}")
        if case.expected_split is not None:
            parts = ", ".join(_q(item or "") for item in case.expected_split)
            lines.append("expected_split = [" + parts + "]")
    lines.append("")
    return "\n".join(lines)


def _text(suite: Suite) -> str:
    lines = [
        f"name: {suite.name}",
        f"engine: {suite.engine}",
        f"mode: {suite.mode}",
        f"flags: {suite.flags or '(none)'}",
        f"pattern: {suite.pattern}",
    ]
    for case in suite.tests:
        if case.should_match:
            expect = "match"
        elif case.should_match is False:
            expect = "no-match"
        else:
            expect = "unspecified"
        lines.append(f"- {case.name}: {expect} {case.text!r}")
    return "\n".join(lines) + "\n"


def _flag_bits(flags: object) -> int:
    import re

    bits = 0
    if getattr(flags, "ignorecase", False):
        bits |= re.IGNORECASE
    if getattr(flags, "multiline", False):
        bits |= re.MULTILINE
    if getattr(flags, "dotall", False):
        bits |= re.DOTALL
    if getattr(flags, "verbose", False):
        bits |= re.VERBOSE
    if getattr(flags, "ascii", False):
        bits |= re.ASCII
    return bits


def _q(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'
